import { expect, test } from '@playwright/test'

test('lead happy path: dashboard, equity, time and talent, model, settings threshold changes proposals', async ({ page }) => {
  await page.goto('/l')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Dashboard')
  await page.screenshot({ path: 'e2e/screens/lead-dashboard.png', fullPage: true })
  await page.getByRole('link', { name: 'Equity Snapshot' }).click()
  await expect(page.getByRole('heading', { name: /No real-world slot/ })).toBeVisible()
  await page.screenshot({ path: 'e2e/screens/lead-equity.png', fullPage: true })
  await page.getByRole('link', { name: 'Time and Talent' }).click()
  await expect(page.getByText(/ten points (of|from) target/)).toBeVisible()
  await page.screenshot({ path: 'e2e/screens/lead-time.png', fullPage: true })
  await page.getByRole('link', { name: 'Model Dashboard' }).click()
  await page.screenshot({ path: 'e2e/screens/lead-model.png', fullPage: true })
  await page.getByRole('link', { name: 'Settings' }).click()
  const hint = page.getByText(/workshop proposals with the current threshold/)
  const before = await hint.textContent()
  await page.getByLabel(/Grouping threshold/).fill('6')
  await expect(hint).not.toContainText(before ?? '')
  await page.screenshot({ path: 'e2e/screens/lead-settings.png', fullPage: true })
  await page.getByRole('link', { name: 'Live Board' }).click()
  await page.getByRole('button', { name: /^Tue/ }).click()
  await expect(page.getByText(/students$/).first()).toBeVisible()
  await page.screenshot({ path: 'e2e/screens/lead-live.png', fullPage: true })
  await page.getByRole('link', { name: 'Knowledge Graph' }).click()
  await expect(page.getByRole('heading', { name: 'Argumentative claim' })).toBeVisible()
})
